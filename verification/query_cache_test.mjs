import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { execFileSync } from 'node:child_process';
const root = path.resolve(import.meta.dirname, '..');
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'forgeflow-query-cache-'));
execFileSync(path.join(root, 'console/node_modules/.bin/tsc'), [path.join(root, 'console/src/app/query-cache.ts'), '--target', 'ES2022', '--module', 'ES2022', '--skipLibCheck', '--outDir', temp]);
fs.renameSync(path.join(temp, 'query-cache.js'), path.join(temp, 'query-cache.mjs'));
const { QueryCache } = await import(pathToFileURL(path.join(temp, 'query-cache.mjs')));
const tick = async () => { for (let i = 0; i < 12; i++) await Promise.resolve(); };
const pending = []; const calls = [];
const cache = new QueryCache((key, signal) => new Promise((resolve, reject) => { pending.push({ key, signal, resolve, reject }); calls.push(key); }), 20000, 2);
const updates = [];
const one = cache.subscribe('identity-1/p1/tasks?q=a', () => updates.push(cache.get('identity-1/p1/tasks?q=a')));
const two = cache.subscribe('identity-1/p1/tasks?q=a', () => {});
await tick(); assert.equal(calls.length, 1, 'identical consumers deduplicate requests');
pending[0].resolve(['old']); await tick(); assert.deepEqual(cache.get(calls[0]).data, ['old']);
cache.invalidate(key => key.includes('/p1/')); await tick();
assert.deepEqual(cache.get(calls[0]).data, ['old'], 'background refresh retains data');
assert.equal(cache.get(calls[0]).loading, true);
pending[1].reject(new Error('offline')); await tick();
assert.deepEqual(cache.get(calls[0]).data, ['old'], 'offline refresh retains the prior observation');
assert.equal(cache.get(calls[0]).error.message, 'offline');
one(); two(); await tick();
const reuse = cache.subscribe(calls[0], () => {}); await tick(); assert.equal(calls.length, 2, 'navigation uses fresh cached data');
const oldProject = cache.subscribe('identity-1/p2/tasks', () => {}); await tick(); const oldRead = pending.at(-1);
oldProject(); await tick(); assert.equal(oldRead.signal.aborted, true, 'last consumer aborts old project request');
oldRead.resolve(['wrong project']); await tick(); assert.equal(cache.get('identity-1/p2/tasks').data, undefined);
reuse(); await tick();
const staleUser = cache.subscribe('identity-1/p1/tasks', () => {}); await tick(); const priorIdentityRead = pending.at(-1);
cache.clear(); assert.equal(priorIdentityRead.signal.aborted, true, 'auth change aborts prior identity');
const newUser = cache.subscribe('identity-2/p1/tasks', () => {}); await tick();
priorIdentityRead.resolve(['prior identity']); pending.at(-1).resolve(['new identity']); await tick();
assert.deepEqual(cache.get('identity-2/p1/tasks').data, ['new identity']);
assert.equal(cache.get('identity-1/p1/tasks').data, undefined, 'late auth response cannot repopulate cleared cache');
staleUser(); newUser(); await tick();
const remount = cache.subscribe('identity-3/p3', () => {}); remount();
const replacement = cache.subscribe('identity-3/p3', () => {}); await tick();
assert.equal(pending.at(-1).signal.aborted, false, 'StrictMode remount keeps the shared request');
replacement(); await tick();
assert.equal(pending.at(-1).signal.aborted, true);
const result = { status: 'PASS', checks: 12, scope: 'read deduplication, retained stale data, refresh errors, project cancellation, identity isolation, StrictMode', real_model_calls: 0 };
if (process.argv[2]) fs.writeFileSync(process.argv[2], JSON.stringify(result, null, 2) + '\n');
console.log(JSON.stringify(result));
